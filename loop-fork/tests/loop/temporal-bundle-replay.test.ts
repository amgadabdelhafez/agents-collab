/**
 * Can a host on this line take over executions an earlier build left in
 * flight? The generic `temporalWorkflow` keeps each workflow's state machine
 * in memory and rebuilds it by replaying the execution's history (start input
 * and every signal) through this bundle's code, so a worker on a new bundle
 * replays histories an old bundle wrote.
 *
 * The earlier builds (tests/support/temporal-replay-builds.ts): the V2 line
 * at 40097564 (r2), ef570282 (r3), 00094c66 (r4) and c7646ed3 (the round-5
 * base), and 455ccc32, the build of the live orchestration service, whose V1
 * messages, governess beats and task graphs this line inherits on upgrade.
 *
 * Three checks, because Temporal's own check sees only part of it:
 *
 * 1. Replay (Worker.runReplayHistories) of histories recorded by the shipped
 *    bundles of those builds (tests/fixtures/temporal-replay, regenerated by
 *    scripts/record-temporal-replay-histories.ts) against this checkout's
 *    bundle, both the shipped (committed generated) bundle and a fresh build
 *    of the source. Replay fails on a workflow task failure, or on a command
 *    event in the history the bundle does not issue. `temporalWorkflow`
 *    issues no commands at all (no activity, timer or child), so these
 *    histories hold no command events: replay cannot see a change in what a
 *    signal does to the state, nor an added command.
 * 2. Recorded answers: each recorded history's start input and signals, sent
 *    again byte for byte to a worker on this checkout's bundle, must leave
 *    every query the callers send (status, `delivery_request`,
 *    `delivery_pending`, `ready`, the governess journal reads), the
 *    inspection and every command outcome exactly as the recording build
 *    answered them. Needs only the fixtures.
 * 3. A live handoff on a local Temporal dev server: the old bundle's worker
 *    leaves the executions in flight, a worker on the new bundle (no cache,
 *    so it replays the history for every task) must answer every query
 *    exactly as the old one did, and finishing the work on the new bundle
 *    must end in the same state as finishing it on the old one. Both bundles
 *    are taken from git, so this needs the source commits in the clone.
 */

