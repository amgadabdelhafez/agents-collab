/**
 * Can a host on this line take over executions an earlier build left in
 * flight? The generic `temporalWorkflow` keeps each workflow's state machine
 * in memory and rebuilds it by replaying the execution's history (start input
 * and every signal) through this bundle's code, so a worker on a new bundle
 * replays histories an old bundle wrote.
 *
 * Two checks, because Temporal's own check sees only part of it:
 *
 * 1. Replay (Worker.runReplayHistories) of histories recorded by the shipped
 *    bundles of 40097564 and ef570282 (tests/fixtures/temporal-replay,
 *    regenerated by scripts/record-temporal-replay-histories.ts) against this
 *    checkout's bundle, both the shipped (committed generated) bundle and a
 *    fresh build of the source. Replay fails on a workflow task failure, or
 *    on a command event in the history the bundle does not issue.
 *    `temporalWorkflow` issues no commands at all (no activity, timer or
 *    child), so these histories hold no command events: replay cannot see a
 *    change in what a signal does to the state, nor an added command.
 * 2. A live handoff on a local Temporal dev server: the old bundle's worker
 *    leaves the executions in flight, a worker on the new bundle (no cache,
 *    so it replays the history for every task) must answer every query
 *    exactly as the old one did, and finishing the work on the new bundle
 *    must end in the same state as finishing it on the old one. Both bundles
 *    are taken from git, so this needs the source commits in the clone.
 */

setDefaultTimeout(120_000);

const FIXTURE_DIR = join(LOOP_FORK_ROOT, "tests/fixtures/temporal-replay");
const WORKFLOWS_PATH = join(LOOP_FORK_ROOT, "src/loop/temporal-workflow.ts");

interface ManifestHistory {
  commands: string[];
  file: string;
  inFlight: { phase?: string; status: string };
  scenario: string;
  snapshot: ReplaySnapshot;
  workflowId: string;
  workflowType: string;
}

interface ManifestSource {
  bundleSha256: string;
  committedBundleDiffersFromSourceIn: string[];
  histories: ManifestHistory[];
  label: string;
  ref: string;
}

/** This line's contract derivations, as `replayIdentityOf` takes them. */
const currentContract = {
  deriveSupervisorMessageV2LegacyWorkflowId,
  deriveSupervisorMessageV2ResultGraphWorkflowId,
  deriveSupervisorMessageV2WorkflowId,
  parseSupervisorMessageV2Input,
  SupervisorResultGraphKey,
} as unknown as Parameters<typeof replayIdentityOf>[0];

const manifest = JSON.parse(
  readFileSync(join(FIXTURE_DIR, "manifest.json"), "utf8")
) as { schema: string; sources: ManifestSource[] };

interface HistoryEvent {
  eventType: string;
  workflowExecutionStartedEventAttributes?: { workflowType: { name: string } };
  workflowTaskCompletedEventAttributes?: { identity?: string };
}

const historyOf = (entry: ManifestHistory): { events: HistoryEvent[] } =>
  JSON.parse(readFileSync(join(FIXTURE_DIR, entry.file), "utf8"));

const silentLogger = {
  debug: () => undefined,
  error: () => undefined,
  info: () => undefined,
  log: () => undefined,
  trace: () => undefined,
  warn: () => undefined,
};

/** Replay every history; the result per workflow id is its error, if any. */
const replay = async (
  bundle: { code: string } | { workflowsPath: string },
  histories: readonly { history: unknown; workflowId: string }[]
): Promise<Map<string, string>> => {
  const results = new Map<string, string>();
  const options =
    "code" in bundle
      ? { workflowBundle: { code: bundle.code } }
      : { workflowsPath: bundle.workflowsPath };
  for await (const result of Worker.runReplayHistories(
    { ...options, replayName: "temporal-bundle-replay" },
    histories
  )) {
    results.set(
      result.workflowId,
      result.error ? `${result.error.name}: ${result.error.message}` : "ok"
    );
  }
  return results;
};

const recorded = (source: ManifestSource) =>
  source.histories.map((entry) => ({
    history: historyOf(entry),
    workflowId: entry.workflowId,
  }));

describe("recorded in-flight histories", () => {
  test("cover both earlier lines, every scenario, as recorded by their shipped bundles", () => {
    expect(manifest.schema).toBe("temporal-replay-fixtures.v1");
    expect(manifest.sources.map((source) => source.ref)).toEqual(
      REPLAY_SOURCES.map((source) => source.ref)
    );
    const names = replayScenarios(
      replayIdentityOf(currentContract, "names", "legacy", "names")
    ).map((scenario) => scenario.name);
    for (const source of manifest.sources) {
      expect(source.histories.map((entry) => entry.scenario)).toEqual(names);
      expect(source.bundleSha256).toMatch(/^[a-f0-9]{64}$/);
    }
  });

  test("each history is the open execution its snapshot describes", () => {
    for (const source of manifest.sources) {
      for (const entry of source.histories) {
        const events = historyOf(entry).events;
        const label = `${source.label} ${entry.scenario}`;
        expect(
          events[0]?.workflowExecutionStartedEventAttributes?.workflowType.name,
          label
        ).toBe("temporalWorkflow");
        // Still in flight: no close event, the last task completed.
        expect(events.at(-1)?.eventType, label).toBe(
          "EVENT_TYPE_WORKFLOW_TASK_COMPLETED"
        );
        expect(
          events.filter(
            (event) =>
              event.eventType === "EVENT_TYPE_WORKFLOW_EXECUTION_SIGNALED"
          ).length,
          label
        ).toBe(entry.commands.length);
        expect(Object.keys(entry.snapshot.outcomes), label).toEqual(
          entry.commands
        );
        expect<string>(entry.snapshot.inspection.status, label).toBe(
          entry.inFlight.status
        );
        expect(phaseOf(entry.snapshot.status), label).toBe(
          entry.inFlight.phase
        );
        expect(entry.snapshot.inspection.workflowType, label).toBe(
          entry.workflowType
        );
      }
    }
  });
});

describe("Temporal replay of the recorded histories on this checkout's bundle", () => {
  const shipped = new Map<string, Map<string, string>>();
  const fromSource = new Map<string, Map<string, string>>();
  let refusing = new Map<string, string>();
  let timerFirst = new Map<string, string>();
  const everyHistory = () => manifest.sources.flatMap(recorded);
  const bundleOf = async (workflowsPath: string) =>
    (
      await bundleWorkflowCode({
        logger: silentLogger as never,
        workflowsPath,
      })
    ).code;

  beforeAll(async () => {
    const sourceCode = await bundleOf(WORKFLOWS_PATH);
    for (const source of manifest.sources) {
      shipped.set(
        source.label,
        await replay({ code: currentBundleCode() }, recorded(source))
      );
      fromSource.set(
        source.label,
        await replay({ code: sourceCode }, recorded(source))
      );
    }
    refusing = await replay(
      {
        code: await bundleOf(
          join(FIXTURE_DIR, "refuse-last-signal-workflow.ts")
        ),
      },
      everyHistory()
    );
    timerFirst = await replay(
      { code: await bundleOf(join(FIXTURE_DIR, "timer-first-workflow.ts")) },
      everyHistory()
    );
  }, 180_000);

  for (const source of manifest.sources) {
    for (const entry of source.histories) {
      test(`${source.label} ${entry.scenario} replays on the shipped bundle and on a build of the current source`, () => {
        expect(shipped.get(source.label)?.get(entry.workflowId)).toBe("ok");
        expect(fromSource.get(source.label)?.get(entry.workflowId)).toBe("ok");
      });
    }
  }

  test("control: a bundle that fails a history's last recorded signal fails that history's replay", () => {
    const entries = manifest.sources.flatMap((source) => source.histories);
    expect(refusing.size).toBe(entries.length);
    for (const entry of entries) {
      const result = refusing.get(entry.workflowId);
      if (entry.commands.length === 0) {
        expect(result, entry.workflowId).toBe("ok");
      } else {
        expect(result, entry.workflowId).toStartWith(
          "ReplayError: Replay failed due workflow task failure"
        );
      }
    }
    // Most histories hold commands, so the control is not vacuous.
    expect(entries.filter((entry) => entry.commands.length > 0).length).toBe(
      18
    );
  });

  test("characterization: replay accepts a bundle that adds a timer, because these histories hold no command events", () => {
    // `temporalWorkflow` issues no commands, so no history has a command
    // event for a new command to contradict; @temporalio/worker 1.23.0
    // replays such a bundle without a nondeterminism error. A command added
    // to the current bundle shows up only in the rollback handoff below,
    // where the older bundle meets a command event it does not issue.
    expect([...timerFirst.values()]).toEqual(
      manifest.sources.flatMap((source) => source.histories.map(() => "ok"))
    );
  });
});

interface Side {
  build?: ExtractedBuild;
  code: string;
  contract: Parameters<typeof replayIdentityOf>[0];
  label: string;
  messageIdFormat: "deployment" | "legacy";
  Port: new (
    client: unknown,
    options: { now: () => string; taskQueue: string }
  ) => ReplayPort;
}

const currentSide = (): Side => ({
  code: currentBundleCode(),
  contract: currentContract,
  label: "current",
  // The shipping default: a ledger writes legacy ids until an operator flips.
  messageIdFormat: "legacy",
  Port: TemporalWorkflowPort as unknown as Side["Port"],
});

const sourceSide = async (source: ReplaySource): Promise<Side> => {
  const build = await extractBuild(source);
  const port = (await import(
    join(build.root, "src/loop/temporal-workflow-port.ts")
  )) as { TemporalWorkflowPort: Side["Port"] };
  return {
    build,
    code: build.bundleCode,
    contract: await import(
      join(build.root, "src/loop/supervisor-message-v2-contract.ts")
    ),
    label: source.label,
    messageIdFormat: source.messageIdFormat,
    Port: port.TemporalWorkflowPort,
  };
};

const sourceOf = (label: string): ReplaySource => {
  const source = REPLAY_SOURCES.find((candidate) => candidate.label === label);
  if (!source) {
    throw new Error(`no replay source ${label}`);
  }
  return source;
};

describe("live handoff of in-flight executions between bundles on a local Temporal server", () => {
  let environment: TestWorkflowEnvironment;
  let client: Client;

  beforeAll(async () => {
    environment = await TestWorkflowEnvironment.createLocal();
    client = new Client({
      connection: environment.connection,
      identity: "temporal-bundle-replay-client",
      namespace: environment.namespace,
    });
  }, 180_000);

  afterAll(async () => {
    await environment?.teardown();
  });

  const startWorker = async (
    code: string,
    taskQueue: string,
    identity: string
  ): Promise<() => Promise<void>> => {
    const worker = await Worker.create({
      connection: environment.nativeConnection,
      identity,
      // No cache: every task, query included, replays the whole history.
      maxCachedWorkflows: 0,
      namespace: environment.namespace,
      taskQueue,
      workflowBundle: { code },
    });
    const running = worker.run();
    return async () => {
      worker.shutdown();
      await running;
    };
  };

  const handoffs = [
    { from: "r2-40097564", name: "r2-to-current", to: "current" },
    { from: "r3-ef570282", name: "r3-to-current", to: "current" },
    // The documented rollback target, the other way round.
    { from: "current", name: "current-to-r2", to: "r2-40097564" },
  ] as const;

  for (const [index, handoff] of handoffs.entries()) {
    test(`executions ${handoff.from} left in flight continue on ${handoff.to} exactly as on ${handoff.from}`, async () => {
      const from =
        handoff.from === "current"
          ? currentSide()
          : await sourceSide(sourceOf(handoff.from));
      const to =
        handoff.to === "current"
          ? currentSide()
          : await sourceSide(sourceOf(handoff.to));
      try {
        if (from.label !== "current") {
          const recordedSource = manifest.sources.find(
            (source) => source.label === from.label
          );
          // The live test runs the very bundle the fixtures were recorded on.
          expect(bundleDigest(from.code)).toBe(
            recordedSource?.bundleSha256 ?? "no recorded source"
          );
        }
        const taskQueue = `replay-live-${index}-${process.pid}`;
        const clock = { at: "" };
        const fromPort = new from.Port(client.workflow, {
          now: () => clock.at,
          taskQueue,
        });
        const toPort = new to.Port(client.workflow, {
          now: () => clock.at,
          taskQueue,
        });
        const outcome = (workflowId: string, key: string) =>
          client.workflow
            .getHandle(workflowId)
            .query("workflow-port-command-outcome", key);
        const subjectIdentity = replayIdentityOf(
          from.contract,
          `${handoff.name}-subject`,
          from.messageIdFormat,
          taskQueue
        );
        const controlIdentity = replayIdentityOf(
          from.contract,
          `${handoff.name}-control`,
          from.messageIdFormat,
          taskQueue
        );
        const subjects = replayScenarios(subjectIdentity);
        const controls = replayScenarios(controlIdentity);
        const all = (scenario: ReplayScenario) => [
          ...scenario.before,
          ...scenario.after,
        ];
        const normalized = (
          snapshot: ReplaySnapshot,
          scenario: ReplayScenario,
          identity: ReplayIdentity
        ) => normalizeReplaySnapshot(snapshot, scenario, identity);

        const fromWorker = `${from.label}-worker`;
        const toWorker = `${to.label}-worker`;
        const stopFrom = await startWorker(from.code, taskQueue, fromWorker);
        const before = new Map<string, unknown>();
        const controlFinal = new Map<string, unknown>();
        try {
          for (const scenario of subjects) {
            await startReplayScenario(fromPort, clock, scenario);
            before.set(
              scenario.name,
              normalized(
                await snapshotReplayScenario(
                  fromPort,
                  outcome,
                  scenario,
                  scenario.before
                ),
                scenario,
                subjectIdentity
              )
            );
          }
          // The same work finished entirely on the old bundle.
          for (const scenario of controls) {
            await startReplayScenario(fromPort, clock, scenario);
            await runReplayCommands(fromPort, clock, scenario, scenario.after);
            controlFinal.set(
              scenario.name,
              normalized(
                await snapshotReplayScenario(
                  fromPort,
                  outcome,
                  scenario,
                  all(scenario)
                ),
                scenario,
                controlIdentity
              )
            );
          }
        } finally {
          await stopFrom();
        }

        const stopTo = await startWorker(to.code, taskQueue, toWorker);
        const answered = new Map<string, unknown>();
        const finished = new Map<string, unknown>();
        const finalStates = new Map<string, unknown>();
        try {
          for (const scenario of subjects) {
            answered.set(
              scenario.name,
              normalized(
                await snapshotReplayScenario(
                  toPort,
                  outcome,
                  scenario,
                  scenario.before
                ),
                scenario,
                subjectIdentity
              )
            );
            await runReplayCommands(toPort, clock, scenario, scenario.after);
            const final = await snapshotReplayScenario(
              toPort,
              outcome,
              scenario,
              all(scenario)
            );
            finished.set(
              scenario.name,
              normalized(final, scenario, subjectIdentity)
            );
            finalStates.set(scenario.name, {
              phase: phaseOf(final.status),
              status: final.inspection.status,
            });
          }
        } finally {
          await stopTo();
        }

        for (const scenario of subjects) {
          expect(answered.get(scenario.name), scenario.name).toEqual(
            before.get(scenario.name)
          );
          expect(finished.get(scenario.name), scenario.name).toEqual(
            controlFinal.get(scenario.name)
          );
          expect(finalStates.get(scenario.name), scenario.name).toEqual({
            phase: scenario.final.phase,
            status: scenario.final.status,
          });
        }

        // Each history now holds tasks of both workers and no failed task,
        // and replays whole on the bundle that finished it.
        const histories: { history: unknown; workflowId: string }[] = [];
        for (const scenario of subjects) {
          const history = await client.workflow
            .getHandle(scenario.workflowId)
            .fetchHistory();
          const events = history.events ?? [];
          const completedBy = new Set(
            events
              .map(
                (event) => event.workflowTaskCompletedEventAttributes?.identity
              )
              .filter((identity) => identity)
          );
          expect(completedBy, scenario.name).toEqual(
            new Set([fromWorker, toWorker])
          );
          expect(
            events.filter((event) => event.workflowTaskFailedEventAttributes)
              .length,
            scenario.name
          ).toBe(0);
          histories.push({ history, workflowId: scenario.workflowId });
        }
        const replayed = await replay({ code: to.code }, histories);
        expect([...replayed.values()]).toEqual(subjects.map(() => "ok"));
      } finally {
        from.build?.close();
        to.build?.close();
      }
    });
  }
});
