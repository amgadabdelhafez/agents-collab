describe("Temporal replay of the recorded histories on this checkout's bundle", () => {
  const shipped = new Map<string, Map<string, string>>();
  const fromSource = new Map<string, Map<string, string>>();
  let refusing = new Map<string, string>();
  let timerFirst = new Map<string, string>();
  const everyHistory = () => manifest.sources.flatMap(recorded);

  beforeAll(async () => {
    const sourceCode = await bundleOf(WORKFLOWS_PATH);
    for (const source of manifest.sources) {
      shipped.set(
        source.label,
        await replay({ code: currentBundleCode() }, recorded(source))
      );
      fromSource.set(
        source.label,
        await replay({ code: sourceCode }, recorded(source))
      );
    }
    refusing = await replay(
      {
        code: await bundleOf(
          join(FIXTURE_DIR, "refuse-last-signal-workflow.ts")
        ),
      },
      everyHistory()
    );
    timerFirst = await replay(
      { code: await bundleOf(join(FIXTURE_DIR, "timer-first-workflow.ts")) },
      everyHistory()
    );
  }, 180_000);

  for (const source of manifest.sources) {
    for (const entry of source.histories) {
      test(`${source.label} ${entry.scenario} replays on the shipped bundle and on a build of the current source`, () => {
        expect(shipped.get(source.label)?.get(entry.workflowId)).toBe("ok");
        expect(fromSource.get(source.label)?.get(entry.workflowId)).toBe("ok");
      });
    }
  }

  test("control: a bundle that fails a history's last recorded signal fails that history's replay", () => {
    const entries = everyEntry();
    expect(refusing.size).toBe(entries.length);
    for (const entry of entries) {
      const result = refusing.get(entry.workflowId);
      if (entry.commands.length === 0) {
        expect(result, entry.workflowId).toBe("ok");
      } else {
        expect(result, entry.workflowId).toStartWith(
          "ReplayError: Replay failed due workflow task failure"
        );
      }
    }
    // Most histories hold commands, so the control is not vacuous: nine of
    // eleven on each V2 line, fourteen of sixteen at 455ccc32.
    expect(entries.filter((entry) => entry.commands.length > 0).length).toBe(
      50
    );
  });

  test("characterization: replay accepts a bundle that adds a timer, because these histories hold no command events", () => {
    // `temporalWorkflow` issues no commands, so no history has a command
    // event for a new command to contradict; @temporalio/worker 1.23.0
    // replays such a bundle without a nondeterminism error. A command added
    // to the current bundle shows up only in the rollback handoffs below,
    // where the older bundle meets a command event it does not issue.
    expect([...timerFirst.values()]).toEqual(everyEntry().map(() => "ok"));
  });
});

interface WorkflowCommandArg {
  kind: "cancel" | "signal";
  requestId: string;
}

interface RecordedRun {
  signals: { arg: WorkflowCommandArg; name: string }[];
  start: unknown;
}

/** The start argument and every signal, decoded from a recorded history. */
const recordedRunOf = (entry: ManifestHistory): RecordedRun => {
  const history = historyFromJSON(historyOf(entry));
  const decode = (payloads: unknown): unknown => {
    const [payload] = (payloads ?? []) as Parameters<
      typeof defaultPayloadConverter.fromPayload
    >[0][];
    if (!payload) {
      throw new Error(`${entry.file}: an event without its payload`);
    }
    return defaultPayloadConverter.fromPayload(payload);
  };
  let start: unknown;
  const signals: RecordedRun["signals"] = [];
  for (const event of history.events ?? []) {
    const started = event.workflowExecutionStartedEventAttributes;
    if (started) {
      start = decode(started.input?.payloads);
    }
    const signaled = event.workflowExecutionSignaledEventAttributes;
    if (signaled) {
      signals.push({
        arg: decode(signaled.input?.payloads) as WorkflowCommandArg,
        name: signaled.signalName ?? "",
      });
    }
  }
  if (start === undefined) {
    throw new Error(`${entry.file}: no start event`);
  }
  return { signals, start };
};

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

describe("recorded answers: each recorded execution, sent again to this checkout's bundle, answers every query as the recording build did", () => {
  let environment: TestWorkflowEnvironment;
  let client: Client;
  let sourceCode = "";

  beforeAll(async () => {
    environment = await TestWorkflowEnvironment.createLocal();
    client = new Client({
      connection: environment.connection,
      identity: "temporal-bundle-replay-client",
      namespace: environment.namespace,
    });
    sourceCode = await bundleOf(WORKFLOWS_PATH);
  }, 180_000);

  afterAll(async () => {
    await environment?.teardown();
  });

  const bundles = [
    { code: () => currentBundleCode(), name: "the shipped bundle" },
    { code: () => sourceCode, name: "a build of the current source" },
  ];

  for (const [index, bundle] of bundles.entries()) {
    test(`${bundle.name}: every recorded start and signal, sent again, leaves the inspection, every command outcome and every query answer as recorded`, async () => {
      const taskQueue = `replay-recorded-${index}-${process.pid}`;
      const worker = await Worker.create({
        connection: environment.nativeConnection,
        identity: `recorded-answers-${index}`,
        // No cache: every query replays the execution's whole history.
        maxCachedWorkflows: 0,
        namespace: environment.namespace,
        taskQueue,
        workflowBundle: { code: bundle.code() },
      });
      const running = worker.run();
      const port = new TemporalWorkflowPort(client.workflow, { taskQueue });
      const outcome = (workflowId: string, key: string) =>
        client.workflow
          .getHandle(workflowId)
          .query("workflow-port-command-outcome", key);
      const answered = new Map<string, ReplaySnapshot>();
      try {
        await Promise.all(
          manifest.sources.map(async (source) => {
            for (const entry of source.histories) {
              const run = recordedRunOf(entry);
              const handle = await client.workflow.start("temporalWorkflow", {
                args: [run.start],
                taskQueue,
                workflowId: entry.workflowId,
              });
              for (const signal of run.signals) {
                await handle.signal(signal.name, signal.arg);
                const key = `${signal.arg.kind}:${signal.arg.requestId}`;
                for (let attempt = 0; ; attempt += 1) {
                  if (await outcome(entry.workflowId, key)) {
                    break;
                  }
                  if (attempt > 500) {
                    throw new Error(`${entry.file}: no outcome for ${key}`);
                  }
                  await sleep(10);
                }
              }
              answered.set(
                `${source.label} ${entry.scenario}`,
                await snapshotReplayExecution(
                  port,
                  outcome,
                  { queries: entry.queries, workflowId: entry.workflowId },
                  entry.commands
                )
              );
              // Frees the id for the other bundle's run on this server.
              await handle.terminate("recorded answers compared");
            }
          })
        );
      } finally {
        worker.shutdown();
        await running;
      }
      for (const source of manifest.sources) {
        for (const entry of source.histories) {
          const name = `${source.label} ${entry.scenario}`;
          expect(answered.get(name), name).toEqual(entry.snapshot);
        }
      }
      expect(answered.size).toBe(everyEntry().length);
    }, 300_000);
  }
});

interface Side {
  build?: ExtractedBuild;
  code: string;
  contract?: ReplayContractModule;
  label: string;
  messageIdFormat: "deployment" | "legacy";
  Port: new (
    client: unknown,
    options: { now: () => string; taskQueue: string }
  ) => ReplayPort;
}

const currentSide = (): Side => ({
  code: currentBundleCode(),
  contract: currentContract,
  label: "current",
  // The shipping default: a ledger writes legacy ids until an operator flips.
  messageIdFormat: "legacy",
  Port: TemporalWorkflowPort as unknown as Side["Port"],
});

const sourceSide = async (source: ReplaySource): Promise<Side> => {
  const build = await extractBuild(source);
  const port = (await import(
    join(build.root, "src/loop/temporal-workflow-port.ts")
  )) as { TemporalWorkflowPort: Side["Port"] };
  return {
    build,
    code: build.bundleCode,
    ...(build.contract ? { contract: build.contract } : {}),
    label: source.label,
    messageIdFormat: source.messageIdFormat,
    Port: port.TemporalWorkflowPort,
  };
};

const sourceOf = (label: string): ReplaySource => {
  const source = REPLAY_SOURCES.find((candidate) => candidate.label === label);
  if (!source) {
    throw new Error(`no replay source ${label}`);
  }
  return source;
};

describe("live handoff of in-flight executions between bundles on a local Temporal server", () => {
  let environment: TestWorkflowEnvironment;
  let client: Client;

  beforeAll(async () => {
    environment = await TestWorkflowEnvironment.createLocal();
    client = new Client({
      connection: environment.connection,
      identity: "temporal-bundle-replay-client",
      namespace: environment.namespace,
    });
  }, 180_000);

  afterAll(async () => {
    await environment?.teardown();
  });

  const startWorker = async (
    code: string,
    taskQueue: string,
    identity: string
  ): Promise<() => Promise<void>> => {
    const worker = await Worker.create({
      connection: environment.nativeConnection,
      identity,
      // No cache: every task, query included, replays the whole history.
      maxCachedWorkflows: 0,
      namespace: environment.namespace,
      taskQueue,
      workflowBundle: { code },
    });
    const running = worker.run();
    return async () => {
      worker.shutdown();
      await running;
    };
  };

  const handoffs = [
    { from: "r2-40097564", name: "r2-to-current", to: "current" },
    { from: "r3-ef570282", name: "r3-to-current", to: "current" },
    { from: "r4-00094c66", name: "r4-to-current", to: "current" },
    { from: "r5base-c7646ed3", name: "r5base-to-current", to: "current" },
    // The live service's build: what an upgrade of the service inherits.
    { from: "deployed-455ccc32", name: "deployed-to-current", to: "current" },
    // The documented rollback targets, the other way round.
    { from: "current", name: "current-to-r2", to: "r2-40097564" },
    { from: "current", name: "current-to-deployed", to: "deployed-455ccc32" },
  ] as const;

  for (const [index, handoff] of handoffs.entries()) {
    test(`executions ${handoff.from} left in flight continue on ${handoff.to} exactly as on ${handoff.from}`, async () => {
      const from =
        handoff.from === "current"
          ? currentSide()
          : await sourceSide(sourceOf(handoff.from));
      const to =
        handoff.to === "current"
          ? currentSide()
          : await sourceSide(sourceOf(handoff.to));
      try {
        // The family of the earlier build decides what both sides run.
        const family = sourceOf(
          handoff.from === "current" ? handoff.to : handoff.from
        ).family;
        for (const side of [from, to]) {
          if (side.label !== "current") {
            const recordedSource = manifest.sources.find(
              (source) => source.label === side.label
            );
            // The live test runs the very bundle the fixtures were recorded
            // on (for 455ccc32, 4439b2e7's blob-identical copy of it).
            expect(bundleDigest(side.code)).toBe(
              recordedSource?.bundleSha256 ?? "no recorded source"
            );
          }
        }
        const taskQueue = `replay-live-${index}-${process.pid}`;
        const clock = { at: "" };
        const fromPort = new from.Port(client.workflow, {
          now: () => clock.at,
          taskQueue,
        });
        const toPort = new to.Port(client.workflow, {
          now: () => clock.at,
          taskQueue,
        });
        const outcome = (workflowId: string, key: string) =>
          client.workflow
            .getHandle(workflowId)
            .query("workflow-port-command-outcome", key);
        const scenariosNamed = (label: string) =>
          replayScenariosFor({
            ...(from.contract ? { contract: from.contract } : {}),
            deployment: taskQueue,
            family,
            label,
            messageIdFormat: from.messageIdFormat,
          });
        const subjectLabel = `${handoff.name}-subject`;
        const controlLabel = `${handoff.name}-control`;
        const subjects = scenariosNamed(subjectLabel);
        const controls = scenariosNamed(controlLabel);
        const all = (scenario: ReplayScenario) => [
          ...scenario.before,
          ...scenario.after,
        ];

        const fromWorker = `${from.label}-worker`;
        const toWorker = `${to.label}-worker`;
        const stopFrom = await startWorker(from.code, taskQueue, fromWorker);
        const before = new Map<string, ReplaySnapshot>();
        const controlFinal = new Map<string, unknown>();
        try {
          for (const scenario of subjects) {
            await startReplayScenario(fromPort, clock, scenario);
            before.set(
              scenario.name,
              await snapshotReplayScenario(
                fromPort,
                outcome,
                scenario,
                scenario.before
              )
            );
          }
          // The same work finished entirely on the old bundle.
          for (const scenario of controls) {
            await startReplayScenario(fromPort, clock, scenario);
            await runReplayCommands(fromPort, clock, scenario, scenario.after);
            controlFinal.set(
              scenario.name,
              normalizeReplaySnapshot(
                await snapshotReplayScenario(
                  fromPort,
                  outcome,
                  scenario,
                  all(scenario)
                ),
                scenario,
                controlLabel
              )
            );
          }
        } finally {
          await stopFrom();
        }

        const stopTo = await startWorker(to.code, taskQueue, toWorker);
        const answered = new Map<string, ReplaySnapshot>();
        const finished = new Map<string, unknown>();
        const finalStates = new Map<string, unknown>();
        try {
          for (const scenario of subjects) {
            answered.set(
              scenario.name,
              await snapshotReplayScenario(
                toPort,
                outcome,
                scenario,
                scenario.before
              )
            );
            await runReplayCommands(toPort, clock, scenario, scenario.after);
            const final = await snapshotReplayScenario(
              toPort,
              outcome,
              scenario,
              all(scenario)
            );
            finished.set(
              scenario.name,
              normalizeReplaySnapshot(final, scenario, subjectLabel)
            );
            finalStates.set(scenario.name, {
              phase: snapshotPhaseOf(final),
              status: final.inspection.status,
            });
          }
        } finally {
          await stopTo();
        }

        for (const scenario of subjects) {
          // The same execution: every answer exactly as before, ids and all.
          expect(answered.get(scenario.name), scenario.name).toEqual(
            before.get(scenario.name) as ReplaySnapshot
          );
          expect(finished.get(scenario.name), scenario.name).toEqual(
            controlFinal.get(scenario.name)
          );
          expect(finalStates.get(scenario.name), scenario.name).toEqual({
            phase: scenario.final.phase,
            status: scenario.final.status,
          });
        }

        // Each history now holds tasks of both workers and no failed task,
        // and replays whole on the bundle that finished it.
        const histories: { history: unknown; workflowId: string }[] = [];
        for (const scenario of subjects) {
          const history = await client.workflow
            .getHandle(scenario.workflowId)
            .fetchHistory();
          const events = history.events ?? [];
          const completedBy = new Set(
            events
              .map(
                (event) => event.workflowTaskCompletedEventAttributes?.identity
              )
              .filter((identity) => identity)
          );
          expect(completedBy, scenario.name).toEqual(
            new Set([fromWorker, toWorker])
          );
          expect(
            events.filter((event) => event.workflowTaskFailedEventAttributes)
              .length,
            scenario.name
          ).toBe(0);
          histories.push({ history, workflowId: scenario.workflowId });
        }
        const replayed = await replay({ code: to.code }, histories);
        expect([...replayed.values()]).toEqual(subjects.map(() => "ok"));
      } finally {
        from.build?.close();
        to.build?.close();
      }
    });
  }
});
